n = int(input("Введите возраст посетителя от 0 до 120:"))

if n < 0 or n > 120:
    print("Ошибка")
    
if 0 < n < 7:
    print("Билет для вас бесплатный")
elif 7 <= n <= 17:
    print("Вам предоставляется скидка в 50%, билет для обойдется в 150 рублей.")
elif 18 <= n <= 59:
    print("Для вас скидки нет, цена билета 300 рублей.")
else:
    print("Вам предоставляется кидка в 30%, билет вам обойдется в 210 рублей.")
