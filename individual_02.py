a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
g = int(input("Введите третье число: "))

if a % 2 == 1 and b % 2 == 0 and g % 2 == 0:
    print("Первое число нечетное")
elif a % 2 == 0 and b % 2 == 1 and g % 2 == 0:
    print("Второе число нечетное")
elif a % 2 == 0 and b % 2 == 0 and g % 2 == 1:
    print("Третье число нечетное")
elif a % 2 == 1 and b % 2 == 1 and g % 2 == 0:
    print("Первое и второе число нечетное")
elif a % 2 == 0 and b % 2 == 1 and g % 2 == 1:
    print("Второе и третье число нечетное")
elif a % 2 == 1 and b % 2 == 0 and g % 2 == 1:
    print("Первое и третье число нечетное")
elif a % 2 == 1 and b % 2 == 1 and g % 2 == 1:
    print("Все числа нечетные")
else:
    print("Все числа четные")




